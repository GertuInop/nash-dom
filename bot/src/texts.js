export function ukSearchResultsText(total, shown) {
  if (total > shown) {
    return `Найдено: *${total}*. Показаны первые ${shown} — уточните название, если нужной УК нет в списке.`;
  }
  return `Найдено: *${total}*. Выберите свою УК:`;
}

export function formatCompanyCard(company) {
  if (!company) return texts.myUkEmpty;
  return `📞 *Сведения об управляющей компании*

*Название:* ${company.name}
*Город:* ${company.city_slug || 'не указан'}
*Телефон:* ${company.phone || 'не указан'}
*Email:* ${company.email || 'не указан'}
*Адрес:* ${company.address || 'не указан'}
*Статус:* ${company.status}`;
}

export function formatManagerProfile(item) {
  const name = [item.manager_first_name, item.manager_last_name].filter(Boolean).join(' ')
    || 'не указано';
  const username = item.manager_username ? `@${item.manager_username}` : 'не указан';
  return `👤 *Профиль руководителя УК*

*ФИО в MAX:* ${name}
*Username:* ${username}
*MAX ID:* ${item.manager_max_user_id || 'неизвестен'}
*Телефон в профиле:* ${item.manager_phone || 'не указан'}
*Город:* ${item.manager_city_slug || item.city_slug || 'не указан'}

*УК:* ${item.name}
*Телефон УК:* ${item.phone || 'не указан'}
*Email УК:* ${item.email || 'не указан'}
*Адрес УК:* ${item.address || 'не указан'}`;
}
